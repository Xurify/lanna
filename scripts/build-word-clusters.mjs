let out = `/**
 * Word clusters (LangHarness) — the vocabulary units of the path, one per
 * lexical cluster of the hand-authored seed (curriculum/slovak/seed-source.json,
 * spec D2). Generated by scripts/build-word-clusters.mjs; do not edit by hand.
 * Only lemmas the lexicon has are listed, so every cluster can be drilled
 * from real sentences. Numbers are not lexicon lemmas: that cluster is a
 * tutor unit instead (src/core/curriculum.ts).
 */

export interface WordCluster {
	title: string;
	/** The words, for the path line. */
	tagline: string;
	/** lucide icon name (components/lesson/unit-icon.tsx). */
	glyph: string;
	lemmas: readonly string[];
}

export const WORD_CLUSTERS = {
`;
for (const c of S.clusters) {
	if (c.key === "lx-numbers") continue;
	const lemmas = c.words.map((w) => w[0]).filter((w) => lex.has(w.toLocaleLowerCase("sk-SK")));
	if (lemmas.length < 4) {
		console.error(`[word-clusters] ${c.key}: only ${lemmas.length} lemmas in the lexicon, skipped`);
		continue;
	}
	out += `\t"${c.key}": { title: ${JSON.stringify(c.name)}, tagline: ${JSON.stringify(lemmas.slice(0, 5).join(", ") + (lemmas.length > 5 ? "…" : ""))}, glyph: ${JSON.stringify(glyph[c.key] ?? "book")}, lemmas: ${JSON.stringify(lemmas)} },\n`;
}
out += `} as const satisfies Record<string, WordCluster>;

export type WordClusterId = keyof typeof WORD_CLUSTERS;
export const WORD_CLUSTER_IDS = Object.keys(WORD_CLUSTERS) as WordClusterId[];
`;
fs.writeFileSync(path.join(process.cwd(), "src", "core", "word-clusters.ts"), out);
console.log(`[word-clusters] wrote src/core/word-clusters.ts`);
